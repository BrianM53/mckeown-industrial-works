/** "/" | "/mckeown-industrial-works/" — always starts and ends with a slash. */
export function normalizeBasePath(input: string | undefined | null): string {
  let p = (input ?? '').trim()
  if (!p || p === '.' || p === './') return '/'
  if (/^[a-z][a-z0-9+.-]*:/i.test(p)) {
    // A full URL was given; keep only its path.
    try {
      p = new URL(p).pathname
    } catch {
      return '/'
    }
  }
  if (!p.startsWith('/')) p = `/${p}`
  if (!p.endsWith('/')) p = `${p}/`
  return p.replace(/\/{2,}/g, '/')
}

/** Absolute http(s) URL with a trailing slash, or throws with a helpful message. */
export function normalizeSiteUrl(input: string): string {
  const raw = input.trim()
  let u: URL
  try {
    u = new URL(raw)
  } catch {
    throw new Error(`SITE_URL must be an absolute URL (got "${input}")`)
  }
  if (u.protocol !== 'https:' && u.protocol !== 'http:') throw new Error(`SITE_URL must use http(s) (got "${input}")`)
  u.hash = ''
  u.search = ''
  if (!u.pathname.endsWith('/')) u.pathname = `${u.pathname}/`
  return u.toString()
}

/**
 * Public site URL for canonical/OG tags: SITE_URL if set, else the host's own production
 * URL when building on Netlify or Vercel, else the GitHub Pages default.
 */
export function resolveSiteUrl(env: Record<string, string | undefined>): string {
  if (env.SITE_URL?.trim()) return normalizeSiteUrl(env.SITE_URL)
  if (env.NETLIFY === 'true' && env.URL) return normalizeSiteUrl(env.URL)
  if (env.VERCEL === '1' && env.VERCEL_PROJECT_PRODUCTION_URL) return normalizeSiteUrl(`https://${env.VERCEL_PROJECT_PRODUCTION_URL}`)
  return DEFAULT_SITE_URL
}

/** True for absolute http(s) links that leave the site (rendered as new-tab safe anchors). */
export function isExternalHref(href: string): boolean {
  return /^https?:\/\//i.test(href)
}

/**
 * Resolves an owner-configured asset path (e.g. RESUME.pdfUrl = 'resume/Brian-McKeown-Resume.pdf')
 * against the site base path. Absolute URLs and root-relative paths are returned unchanged.
 */
export function resolveSiteHref(basePath: string, href: string): string {
  if (isExternalHref(href) || href.startsWith('/') || href.startsWith('#') || /^[a-z]+:/i.test(href)) return href
  return `${normalizeBasePath(basePath)}${href.replace(/^\.\//, '')}`
}

