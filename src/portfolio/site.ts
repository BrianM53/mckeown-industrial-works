/** Shortens text to at most `max` characters at a word boundary, adding an ellipsis. */
export function clampText(text: string, max: number): string {
  const t = text.replace(/\s+/g, ' ').trim()
  if (t.length <= max) return t
  const cut = t.slice(0, max - 1)
  // Keep the last word when the cut falls exactly on a space; otherwise back up to the previous one.
  const atBoundary = /\s/.test(t[max - 1] ?? '')
  const at = cut.lastIndexOf(' ')
  const kept = atBoundary ? cut : at > max * 0.6 ? cut.slice(0, at) : cut
  return `${kept.replace(/[\s,;:.–—-]+$/, '')}…`
}
