/**
 * World composition. Each module is lazy-loaded into its own isolated slot.
 * Integrator-owned: modules do not edit this file — they own their index.tsx.
 */
/**
 * Dynamic import with one retry after a short pause: covers transient network failures
 * (and a stale chunk right after a deploy) before the slot falls back to its error state.
 */
function withRetry<T>(load: () => Promise<T>, delayMs = 800): () => Promise<T> {
  return () => load().catch(() => new Promise<T>((resolve, reject) => setTimeout(() => load().then(resolve, reject), delayMs)))
}

