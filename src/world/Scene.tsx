export function Scene() {
  return (
    <>
      <SimDriver />
      <PerfMonitor />
      <Suspense fallback={null}>
        <Physics gravity={[0, -18, 0]} timeStep={1 / 60} interpolate colliders={false}>
          <WorldBase />
          {MODULES.map((m) => (
            <ModuleSlot key={m.name} name={m.name} component={m.component} />
          ))}
        </Physics>
      </Suspense>
      <ReadySignal />
    </>
  )
}

/** Drives the simulation clock once per rendered frame and starts global systems. */
function SimDriver() {
  useEffect(() => {
    if (params.seed !== null) factory.setSeed?.(params.seed)
    if (params.timeScale !== null && DEBUG_ENABLED) simClock.timeScale = params.timeScale
    factory.start()
    const offSup = director.addSuppressor(() => {
      const ui = useUIStore.getState()
      return ui.panel !== null || ui.dialogue !== null
    })
    director.setEnabledPredicate(() => !params.noEvents && useSettings.getState().ambientEvents)
    const offDbg = registerDebug('clock', {
      advance: (s: number) => simClock.advance(s),
      setTimeScale: (n: number) => {
        simClock.timeScale = n
      },
      get: () => ({ t: simClock.t, timeScale: simClock.timeScale }),
    })
    const offDir = registerDebug('director', { active: () => director.activeIds(), reset: () => director.reset() })
    const offSettings = registerDebug('settings', {
      get: () => {
        const { set: _set, reset: _reset, ...rest } = useSettings.getState()
        return rest
      },
      set: (patch: Parameters<ReturnType<typeof useSettings.getState>['set']>[0]) => useSettings.getState().set(patch),
    })
    const offCore = registerDebug('core', {
      /** Leak checks: subscriber counts must stay flat across repeated panel opens / resets. */
      counts: () => ({ events: events.count(), clockSubs: simClock.subscriberCount, interactables: listInteractables().length }),
      runtime: () => ({
        player: runtime.player.position.toArray(),
        mode: runtime.player.mode,
        camera: runtime.camera.position.toArray(),
        interior: runtime.world.interior,
        lighting: { ...runtime.lighting },
        fps: Math.round(runtime.frame.fps),
      }),
    })
    return () => {
      factory.stop()
      offSup()
      offDbg()
      offDir()
      offSettings()
      offCore()
    }
  }, [])
  useFrame((_, delta) => simClock.step(delta), -100)
  return null
}

/** Smoothed FPS + automatic quality downgrade when quality is 'auto'. */
function PerfMonitor() {
  const acc = useRef({ frames: 0, time: 0, lowFor: 0 })
  const { gl } = useThree()
  useEffect(
    () =>
      registerDebug('perf', {
        /** Renderer stats of the last frame + smoothed fps (perf script / tests). */
        stats: () => ({
          fps: Math.round(runtime.frame.fps * 10) / 10,
          calls: gl.info.render.calls,
          triangles: gl.info.render.triangles,
          geometries: gl.info.memory.geometries,
          textures: gl.info.memory.textures,
          programs: gl.info.programs?.length ?? 0,
          quality: useGameStore.getState().quality,
        }),
      }),
    [gl],
  )
  useFrame((_, delta) => {
    const a = acc.current
    a.frames++
    a.time += delta
    if (a.time >= 0.5) {
      const fps = a.frames / a.time
      runtime.frame.fps = runtime.frame.fps * 0.6 + fps * 0.4
      a.frames = 0
      a.time = 0
      const s = useSettings.getState()
      const g = useGameStore.getState()
      if (s.quality === 'auto' && params.quality === null && g.status === 'ready' && document.visibilityState === 'visible') {
        if (runtime.frame.fps < 34) a.lowFor += 0.5
        else a.lowFor = Math.max(0, a.lowFor - 0.5)
        if (a.lowFor >= 4) {
          a.lowFor = 0
          if (g.quality === 'high') g.setQuality('medium')
          else if (g.quality === 'medium') g.setQuality('low')
        }
      }
    }
  })
  return null
}

/** Marks the world ready once every module slot has resolved and a few frames rendered. */
function ReadySignal() {
  const frames = useRef(0)
  const done = useRef(false)
  const { gl, scene, camera } = useThree()
  useEffect(() => {
    const onLost = (e: Event) => {
      e.preventDefault()
      useGameStore.getState().setStatus('error')
    }
    const canvas = gl.domElement
    canvas.addEventListener('webglcontextlost', onLost)
    return () => canvas.removeEventListener('webglcontextlost', onLost)
  }, [gl])
  useFrame(() => {
    if (done.current) return
    frames.current++
    const g = useGameStore.getState()
    const allLoaded = g.modulesTotal > 0 && g.modulesLoaded >= g.modulesTotal
    if ((allLoaded && frames.current > 3) || frames.current > 600) {
      done.current = true
      g.setStatus('ready')
      setDebugFlag('ready', true)
      // Warm up shader programs for everything currently in the scene (parallel compile where
      // supported) so first glimpses of machinery don't hitch. Best-effort; failures are harmless.
      try {
        void gl.compileAsync(scene, camera).catch(() => {})
      } catch {
        /* older drivers: ignore */
      }
    }
  })
  return null
}
